// Generates worker/lib/documents/fonts.generated.ts: base64-embedded static
// (non-variable) latin WOFF2 instances for the Documents PDF/preview renderers.
//
// Why: the renderers previously imported Google Fonts at render time. That
// made PDFs depend on CDN availability (silent fallback to Georgia/Helvetica
// when slow) and embedded *variable* fonts, which Chromium's PDF backend
// writes as Type 3 glyphs — old Poppler/Splash viewers show black blocks.
// Static instances embed as ordinary CID TrueType subsets everywhere.
//
// Run after upgrading any @fontsource package: node scripts/generate-document-fonts.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Union of the weights both renderers actually use.
const FONTS = [
  { family: 'Cormorant Garamond', pkg: 'cormorant-garamond', weights: [500, 600, 700] },
  { family: 'Source Sans 3', pkg: 'source-sans-3', weights: [400, 600, 700] },
  { family: 'Space Grotesk', pkg: 'space-grotesk', weights: [500, 700] },
  { family: 'Manrope', pkg: 'manrope', weights: [400, 600, 700] },
  { family: 'Fraunces', pkg: 'fraunces', weights: [600, 700] },
  { family: 'Nunito Sans', pkg: 'nunito-sans', weights: [400, 600, 700] },
];

const entries = [];
for (const font of FONTS) {
  for (const weight of font.weights) {
    const file = join(root, 'node_modules', '@fontsource', font.pkg, 'files', `${font.pkg}-latin-${weight}-normal.woff2`);
    const base64 = readFileSync(file).toString('base64');
    entries.push({ family: font.family, weight, base64 });
  }
}

const byFamily = {};
for (const entry of entries) {
  byFamily[entry.family] ??= {};
  byFamily[entry.family][entry.weight] = entry.base64;
}

const output = `// AUTO-GENERATED by scripts/generate-document-fonts.mjs — do not edit.
// Static latin WOFF2 instances (base64) for deterministic, self-contained
// PDF/preview rendering. See the generator script for the rationale.

const FONT_DATA: Record<string, Record<number, string>> = ${JSON.stringify(byFamily, null, 2)};

/**
 * Inline @font-face rules for the given families. Only families/weights known
 * to this module are emitted; unknown names are ignored (CSS fallbacks apply).
 */
export function documentFontFaceCss(families: string[]): string {
  const rules: string[] = [];
  for (const family of families) {
    const weights = FONT_DATA[family];
    if (!weights) continue;
    for (const [weight, base64] of Object.entries(weights)) {
      rules.push(
        \`@font-face { font-family: '\${family}'; font-style: normal; font-weight: \${weight}; font-display: block; src: url(data:font/woff2;base64,\${base64}) format('woff2'); }\`,
      );
    }
  }
  return rules.join('\\n');
}
`;

const outPath = join(root, 'worker', 'lib', 'documents', 'fonts.generated.ts');
writeFileSync(outPath, output);
const totalKb = Math.round(entries.reduce((sum, entry) => sum + entry.base64.length, 0) / 1024);
console.log(`wrote ${outPath} — ${entries.length} faces, ~${totalKb} KB base64`);
